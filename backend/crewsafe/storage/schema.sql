-- CrewSafe Postgres schema (Layer 3). Load once with `psql "$DATABASE_URL" -f schema.sql`.
-- Natural keys make every write idempotent under at-least-once delivery.

CREATE TABLE IF NOT EXISTS sites (
    id               INTEGER PRIMARY KEY,          -- EIA plant ID
    name             TEXT NOT NULL,
    county           TEXT NOT NULL,
    latitude         DOUBLE PRECISION NOT NULL,
    longitude        DOUBLE PRECISION NOT NULL,
    capacity_mw      DOUBLE PRECISION NOT NULL,
    flood_zone       TEXT,                         -- FEMA NFHL zone (A, AE, VE, X...)
    fema_sfha        BOOLEAN NOT NULL DEFAULT FALSE,
    fema_coastal     BOOLEAN NOT NULL DEFAULT FALSE,
    fema_score       DOUBLE PRECISION NOT NULL DEFAULT 0.05,
    coastal          BOOLEAN NOT NULL DEFAULT FALSE,
    near_river       BOOLEAN NOT NULL DEFAULT FALSE,
    elevation_ft     DOUBLE PRECISION NOT NULL DEFAULT 30,
    wildlife_habitat DOUBLE PRECISION NOT NULL DEFAULT 0.3
);

-- Cleaned observations with derived features. Columns the API filters on are
-- real columns; the full CleanConditions record is kept in `data`.
CREATE TABLE IF NOT EXISTS conditions (
    site_id    INTEGER NOT NULL REFERENCES sites(id),
    obs_time   TIMESTAMPTZ NOT NULL,
    source     TEXT NOT NULL,
    data_stale BOOLEAN NOT NULL DEFAULT FALSE,
    data       JSONB NOT NULL,
    PRIMARY KEY (site_id, obs_time)
);

CREATE TABLE IF NOT EXISTS scores (
    site_id        INTEGER NOT NULL REFERENCES sites(id),
    computed_at    TIMESTAMPTZ NOT NULL,
    hazard_index   DOUBLE PRECISION NOT NULL,
    model_version  TEXT NOT NULL,
    data_stale     BOOLEAN NOT NULL DEFAULT FALSE,
    data           JSONB NOT NULL,                -- full HazardScore (factors, drivers, adjustments)
    PRIMARY KEY (site_id, computed_at)
);
CREATE INDEX IF NOT EXISTS scores_latest ON scores (site_id, computed_at DESC);

CREATE TABLE IF NOT EXISTS reports (
    id         TEXT PRIMARY KEY,                  -- generated by the app, so retries are idempotent
    site_id    INTEGER REFERENCES sites(id),
    type       TEXT NOT NULL,
    notes      TEXT NOT NULL DEFAULT '',
    reporter   TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    latitude   DOUBLE PRECISION,
    longitude  DOUBLE PRECISION,
    photo_url  TEXT
);
CREATE INDEX IF NOT EXISTS reports_site_time ON reports (site_id, created_at DESC);

CREATE TABLE IF NOT EXISTS alerts (
    id        TEXT PRIMARY KEY,
    site_id   INTEGER NOT NULL REFERENCES sites(id),
    type      TEXT NOT NULL,
    severity  TEXT NOT NULL,
    title     TEXT NOT NULL,
    message   TEXT NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    source    TEXT
);
CREATE INDEX IF NOT EXISTS alerts_site_time ON alerts (site_id, issued_at DESC);

CREATE TABLE IF NOT EXISTS alert_acks (
    alert_id TEXT NOT NULL REFERENCES alerts(id),
    user_id  TEXT NOT NULL,
    acked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (alert_id, user_id)
);

CREATE TABLE IF NOT EXISTS lightning_holds (
    site_id INTEGER PRIMARY KEY REFERENCES sites(id),
    data    JSONB NOT NULL                        -- LightningHold
);

CREATE TABLE IF NOT EXISTS users (
    username      TEXT PRIMARY KEY,
    display_name  TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('supervisor', 'crew'))
);

CREATE TABLE IF NOT EXISTS devices (
    apns_token    TEXT PRIMARY KEY,
    user_id       TEXT NOT NULL,
    platform      TEXT NOT NULL,
    registered_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS devices_user ON devices (user_id);

CREATE TABLE IF NOT EXISTS subscriptions (
    user_id      TEXT PRIMARY KEY,
    data         JSONB NOT NULL,                  -- SiteSubscription
    site_ids     INTEGER[] NOT NULL
);
CREATE INDEX IF NOT EXISTS subscriptions_sites ON subscriptions USING GIN (site_ids);

CREATE TABLE IF NOT EXISTS decision_log (
    id         BIGSERIAL PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL,
    site_id    INTEGER,
    kind       TEXT NOT NULL,
    decision   TEXT NOT NULL,
    reason     TEXT NOT NULL,
    data       JSONB NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS decision_log_site_time ON decision_log (site_id, created_at DESC);
